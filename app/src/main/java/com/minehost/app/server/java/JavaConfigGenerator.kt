package com.minehost.app.server.java

import com.minehost.app.server.ServerConfiguration
import java.io.File

object JavaConfigGenerator {

    fun generateServerProperties(config: ServerConfiguration): String {
        return """
            # Minecraft server properties
            # Generated automatically by MineHost
            server-port=${config.localPort}
            motd=${config.motd.ifBlank { config.serverName }}
            gamemode=${config.gameMode.name.lowercase()}
            difficulty=${config.difficulty.name.lowercase()}
            max-players=${config.maxPlayers}
            pvp=${config.pvpEnabled}
            online-mode=${config.onlineMode}
            allow-flight=${config.allowFlight}
            view-distance=${config.viewDistance}
            simulation-distance=${config.simulationDistance}
            level-name=${config.levelName}
            enable-command-block=${config.enableCommandBlocks}
            spawn-protection=${config.spawnProtection}
            white-list=false
            broadcast-rcon-to-ops=false
            enable-rcon=false
            enable-query=true
            query.port=${config.localPort}
            sync-chunk-writes=true
        """.trimIndent()
    }

    fun generateEula(): String {
        return """
            # By changing the setting below to TRUE you are indicating your agreement to the Mojang EULA (https://aka.ms/MinecraftEULA).
            # Generated by MineHost
            eula=true
        """.trimIndent()
    }

    fun writeConfigurations(serverDir: File, config: ServerConfiguration) {
        serverDir.mkdirs()
        File(serverDir, "server.properties").writeText(generateServerProperties(config))
        File(serverDir, "eula.txt").writeText(generateEula())
    }
}
